-- DAY 2 | 2026-10-07 | 概念：什么是数据库（Mosh 第1-2课）

-- 概念笔记：数据库 = 以易获取形式存储的数据集合
-- DBMS（数据库管理系统）= 管理数据库的软件
--   - 关系型：MySQL / SQL Server / Oracle → 用 SQL 语言
--   - 非关系型（NoSQL）：没有表和关系，有自己的查询语言，不能用 SQL
-- 关系型数据库：数据存在表中，表之间通过关系（键）互相连接
-- SQL = Structured Query Language，读法 S-Q-L 或 sequel
-- 各 DBMS 的 SQL 风格略有不同，但都基于标准 SQL

